CREATE TABLE IF NOT EXISTS customers (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, name VARCHAR(150) NOT NULL, phone VARCHAR(30), email VARCHAR(150), address VARCHAR(500), created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS projects (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, project_name VARCHAR(180) NOT NULL, customer_name VARCHAR(150), location VARCHAR(250), start_date DATE, end_date DATE, status VARCHAR(40) DEFAULT 'Planned', amount DECIMAL(14,2) DEFAULT 0, notes VARCHAR(1000), created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS staff (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, name VARCHAR(150) NOT NULL, role VARCHAR(100), phone VARCHAR(30), email VARCHAR(150), salary DECIMAL(12,2) DEFAULT 0, status VARCHAR(30) DEFAULT 'Active', created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS materials (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, item_name VARCHAR(180) NOT NULL, category VARCHAR(100), quantity DECIMAL(12,2) DEFAULT 0, unit VARCHAR(30), unit_price DECIMAL(12,2) DEFAULT 0, supplier VARCHAR(150), reorder_level DECIMAL(12,2) DEFAULT 0, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS expenses (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, expense_date DATE, category VARCHAR(100), description VARCHAR(250), project_name VARCHAR(180), amount DECIMAL(14,2) DEFAULT 0, paid_to VARCHAR(150), payment_method VARCHAR(50), created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS app_users (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, username VARCHAR(80) UNIQUE NOT NULL, password_hash VARCHAR(255) NOT NULL, display_name VARCHAR(150), role VARCHAR(30) DEFAULT 'ADMIN', active BOOLEAN DEFAULT TRUE, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
